console.log('12. Recently closed overflow can be undone, including overflow after an undo')
await page.evaluate(async () => {
  const { useLibrary } = await window.__peImport('/src/store/library.ts')
  const t = await window.__peImport('/src/store/tabs.ts')
  const doc = t.getDocStore(t.useTabs.getState().activeId).getState().doc
  t.useTabs.getState().openInTab(t.useTabs.getState().activeId, structuredClone(doc))
  useLibrary.setState({ recent: [] })
  for (let i = 0; i < 20; i++) useLibrary.getState().pushRecent(i === 0 ? '最早未保存' : `最近关闭 ${i + 1}`, doc)
})
const recent = () => page.evaluate(async () => (await window.__peImport('/src/store/library.ts')).useLibrary.getState().recent)
const oldest = (await recent()).at(-1)
await page.locator('[data-testid=tab][data-active]').getByTestId('close-tab').click()
await page.getByTestId('confirm-discard').click()
await page.getByTestId('start-page').waitFor()
const overflow = page.locator('[data-sonner-toast]').filter({ hasText: '已从「最近关闭」中移除「最早未保存」' })
await overflow.waitFor()
check((await recent()).length === 20 && !(await recent()).some((r) => r.id === oldest.id), '关闭第 21 份后保留 20 条，最早的移除并提示')
check((await page.getByTestId('start-recent').first().getByTestId('start-recent-unsaved').count()) === 0, '从未保存的最近关闭行没有 ●')
await overflow.getByRole('button', { name: '撤销' }).click()
check((await recent()).length === 21 && JSON.stringify((await recent()).at(-1)) === JSON.stringify(oldest), '撤销原样放回末尾，共 21 条')
const nextRemoved = (await recent()).slice(19)
await page.evaluate(async () => {
  const { useLibrary } = await window.__peImport('/src/store/library.ts')
  const t = await window.__peImport('/src/store/tabs.ts')
  const s = t.useTabs.getState()
  const id = s.activeId
  s.openInTab(id, structuredClone(useLibrary.getState().recent[0].doc))
})
await page.locator('[data-testid=tab][data-active]').getByTestId('close-tab').click()
await page.getByTestId('confirm-discard').click()
await page.getByTestId('start-page').waitFor()
check((await recent()).length === 20, '撤销后再次关闭仍收至 20 条')
for (const r of [...nextRemoved].reverse()) {
  const notification = page.locator('[data-sonner-toast]').filter({ hasText: `已从「最近关闭」中移除「${r.title}」` }).last()
  await notification.getByRole('button', { name: '撤销' }).click()
}
const restored = await recent()
check(restored.length === 22 && nextRemoved.every((r) => restored.some((x) => JSON.stringify(x) === JSON.stringify(r))), '此次移除的两条都有撤销入口，原样恢复')
check(nextRemoved.every((r) => r.id === oldest.id || r.title === '最近关闭 2'), '此次移除的是末尾两条')

