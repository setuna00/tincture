import { chromium } from '@playwright/test'
import { mkdirSync } from 'node:fs'
import { E2E_URL, isolate, resetStore } from './store.mjs'

const theme = process.argv[2] ?? 'light'
const prefix = process.argv[3] ?? 'save'
const width = Number(process.argv[4] ?? 1440)
const out = 'e2e/shots'
mkdirSync(out, { recursive: true })

const browser = await chromium.launch()
const page = await browser.newPage({ viewport: { width, height: 900 }, deviceScaleFactor: 2 })
await isolate(page.context())
const errors = []
page.on('console', (m) => m.type() === 'error' && errors.push(m.text()))
page.on('pageerror', (e) => errors.push(String(e)))
await page.goto(E2E_URL)
await resetStore(page, { theme, seed: null })
await page.reload()
await page.waitForLoadState('networkidle')

let fails = 0
const check = (ok, msg) => {
  console.log(ok ? '  ok ' : '  FAIL', msg)
  if (!ok) fails++
}
const tag = width === 1440 ? '' : `-${width}`
const file = (name) => `${out}/${prefix}-${name}${tag}-${theme}.png`
const clip = async (loc, name, pad = 10) => {
  const b = await loc.boundingBox()
  await page.screenshot({ path: file(name), clip: { x: b.x - pad, y: b.y - pad, width: b.width + pad * 2, height: b.height + pad * 2 } })
  console.log('clip', file(name))
}
const tabs = page.getByTestId('tab')
const unsavedTabs = () => page.locator('[data-testid=tab][data-unsaved]').count()
const saveBtn = page.getByTestId('save-doc')
const dialog = page.getByTestId('confirm-dialog')
const addTag = async (text, section = 0) => {
  const input = page.getByTestId('section').nth(section).getByTestId('tag-input')
  await input.click()
  await input.pressSequentially(`${text},`, { delay: 20 })
  await page.waitForTimeout(150)
}
const tabRow = async (name) => {
  await page.mouse.move(width - 4, 880)
  await page.waitForTimeout(300)
  const a = await tabs.first().boundingBox()
  const z = await tabs.last().boundingBox()
  await page.screenshot({ path: file(name), clip: { x: a.x - 10, y: a.y - 6, width: Math.min(z.x + z.width - a.x + 60, width - a.x + 10), height: a.height + 14 } })
  console.log('clip', file(name))
}

