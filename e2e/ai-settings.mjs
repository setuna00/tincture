import { chromium } from '@playwright/test'
import { mkdirSync } from 'node:fs'
import { GOOD_KEY, MODELS, startFakeAi } from './fake-ai.mjs'
import { E2E_URL, isolate, resetStore, stored } from './store.mjs'

const theme = process.argv[2] ?? 'light'
const prefix = process.argv[3] ?? 'ai-settings'
const width = Number(process.argv[4] ?? 1440)
const out = 'e2e/shots'
mkdirSync(out, { recursive: true })

const fake = await startFakeAi()
const browser = await chromium.launch()
const ctx = await browser.newContext({ viewport: { width, height: 1300 }, deviceScaleFactor: 2 })
await isolate(ctx)
const page = await ctx.newPage()
const errors = []
page.on('console', (m) => m.type() === 'error' && errors.push(m.text()))
page.on('pageerror', (e) => errors.push(String(e)))
await page.goto(E2E_URL)
await resetStore(page, { theme })
await page.goto(new URL('#/settings', E2E_URL).href)
await page.reload()
await page.waitForLoadState('networkidle')

const fails = []
const check = (ok, msg) => (ok ? console.log('ok  ', msg) : (fails.push(msg), console.log('FAIL', msg)))
const name = (n) => `${out}/${prefix}-${n}-${theme}${width === 1440 ? '' : `-${width}`}.png`
const shot = async (loc, n, pad = 12) => {
  await loc.evaluate((el) => el.scrollIntoView({ block: 'nearest' }))
  await page.waitForTimeout(100)
  const b = await loc.boundingBox()
  await page.screenshot({ path: name(n), clip: { x: Math.max(0, b.x - pad), y: Math.max(0, b.y - pad), width: b.width + pad * 2, height: b.height + pad * 2 } })
  console.log('shot', name(n))
}
const group = page.getByTestId('ai-settings')
const svc = page.getByTestId('ai-service')
const status = () => svc.first().getByTestId('ai-service-status').textContent({ timeout: 3000 }).catch(() => '')

await page.getByTestId('settings-nav-ai').click()
await page.waitForTimeout(400)
check(await group.isVisible(), '侧栏点「AI」打开「AI」页')
await page.mouse.move(2, 890)
await shot(group, 'empty')

check((await page.getByTestId('ai-services-nai').innerText()).includes('NovelAI') && (await page.getByTestId('ai-nai-none').innerText()).includes('未添加'), 'NovelAI 一节：未添加 · 添加 NovelAI')
check((await page.getByTestId('ai-services').innerText()).startsWith('其他 AI 服务'), '其他 AI 服务一节')
const chatSet = page.getByTestId('chat-settings')
check((await chatSet.innerText()).includes('位于竖条底部') && (await chatSet.innerText()).includes('Enter 发送，Shift+Enter 换行'), '问 AI 一节：入口默认竖条按钮、发送键默认 Enter')
await page.getByTestId('chat-entry-tab').click()
check((await chatSet.innerText()).includes('位于助手栏顶部，与「模板库」并列'), '入口换成助手栏标签：灰字跟着换')
await page.getByTestId('chat-send-key-shift').click()
check((await chatSet.innerText()).includes('Shift+Enter 发送，Enter 换行'), '发送键换成 Shift+Enter')
const p0 = JSON.parse(await stored(page, 'pe:prefs')).state
check(p0.chatEntry === 'tab' && p0.chatSendKey === 'shift', '存进偏好')
await page.getByTestId('chat-entry-rail').click()
await page.getByTestId('chat-send-key-enter').click()
await page.mouse.move(2, 890)
await page.waitForTimeout(300)
await shot(chatSet, 'chat-section')

await page.getByTestId('ai-add-service').click()
await page.waitForTimeout(300)
check((await svc.count()) === 1 && (await svc.first().getAttribute('data-preset')) === 'deepseek', '添加服务：默认 DeepSeek，展开')
check((await status()) === '未填写 API Key', `没填 key：${await status()}`)
check((await page.getByTestId('ai-service-url-fixed').textContent()) === 'https://api.deepseek.com', '预设的地址只显示、不能改')
await page.getByTestId('ai-service-preset').click()
check((await page.getByRole('option', { name: 'NovelAI' }).count()) === 0, '其他 AI 服务的服务下拉里没有 NovelAI')
await page.getByRole('option', { name: '自定义' }).click()
await page.getByTestId('ai-service-url').fill(fake.url)
await page.getByTestId('ai-service-key').fill('sk-wrong')
await page.getByTestId('ai-service-key').press('Enter')
await page.waitForFunction(() => document.querySelector('[data-testid=ai-service-status]')?.textContent?.startsWith('无法连接'), null, { timeout: 5000 }).catch(() => {})
check((await status()) === '无法连接：API Key 无效', `key 不对：${await status()}`)
check((await svc.first().getByTestId('ai-service-head').locator('span').first().textContent()) === new URL(fake.url).host, '自定义的名字 = 地址的 host')
await page.getByTestId('ai-service-key').fill(GOOD_KEY)
await page.getByTestId('ai-service-key').press('Enter')
await page.waitForFunction(() => document.querySelector('[data-testid=ai-service-status]')?.textContent === '已连接', null, { timeout: 5000 }).catch(() => {})
check((await status()) === '已连接', `key 对了：${await status()}`)
check(fake.requests.filter((r) => r.url === '/v1/models').at(-1)?.auth === `Bearer ${GOOD_KEY}`, '取模型列表带着 key')

await page.getByTestId('ai-service-model-picker').click()
await page.getByTestId('ai-model-menu').waitFor()
check((await page.getByTestId('ai-model-option').allTextContents()).join(',') === MODELS.join(','), '模型下拉 = 取到的列表')
await page.waitForTimeout(250)
await shot(page.getByTestId('ai-model-menu'), 'model-menu', 8)
await page.getByTestId('ai-model-option').first().click()
check((await svc.first().getByTestId('ai-service-model').textContent()) === MODELS[0], '选了模型，行里显示')
await page.getByTestId('ai-service-model-picker').click()
await page.getByTestId('ai-model-search').fill('my-local-model')
await page.getByTestId('ai-model-use').click()
check((await svc.first().getByTestId('ai-service-model').textContent()) === 'my-local-model', '手填的模型')
await page.getByTestId('ai-service-model-picker').click()
await page.getByTestId('ai-model-option').first().click()
await page.mouse.move(2, 890)
await page.waitForTimeout(300)
await shot(svc.first(), 'service-open')

await page.getByTestId('ai-add-rule').click()
await page.waitForTimeout(300)
check(await page.getByTestId('ai-rule-name').evaluate((el) => el === document.activeElement), '添加规则：焦点在名字框')
await page.getByTestId('ai-rule-name').fill('保留画师')
await page.getByTestId('ai-rule-body').fill('不修改「画师」区块。\n其余照要求改。')
check(await svc.first().getAttribute('data-open') === null, '展开规则时服务收起（同时只展开一个）')
await page.getByTestId('ai-add-rule').click()
await page.getByTestId('ai-rule-name').last().fill('只用英文')
await page.getByTestId('ai-rule-on').last().click()
await page.getByTestId('ai-rule-head').last().click()
await page.mouse.move(2, 890)
await page.waitForTimeout(400)
await shot(group, 'filled')

const saved = JSON.parse(await stored(page, 'pe:ai'))
check(saved.state.services.length === 1 && saved.state.services[0].model === MODELS[0] && saved.state.services[0].url === fake.url, '服务存进 pe:ai')
check(saved.state.rules.map((r) => `${r.name}:${r.on}`).join(',') === '保留画师:true,只用英文:false', '规则存进 pe:ai（名字、默认勾选）')
await page.reload()
await page.waitForLoadState('networkidle')
await page.getByTestId('settings-nav-ai').click()
await page.waitForFunction(() => document.querySelector('[data-testid=ai-service-status]')?.textContent === '已连接', null, { timeout: 5000 }).catch(() => {})
check((await status()) === '已连接', '刷新后：打开设置页取一次列表，已连接')
check((await page.getByTestId('ai-rule').count()) === 2, '刷新后规则还在')

await svc.first().getByTestId('ai-service-head').click()
await page.getByTestId('ai-service-delete').click()
check((await svc.count()) === 0, '删除服务')
await page.getByRole('button', { name: '撤销' }).click()
check((await svc.count()) === 1 && (await svc.first().getByTestId('ai-service-model').textContent()) === MODELS[0], '撤销：服务回来了')

await page.getByTestId('ai-add-nai').click()
await page.waitForTimeout(300)
const nai = page.getByTestId('ai-services-nai').getByTestId('ai-service')
check((await nai.count()) === 1 && (await nai.getAttribute('data-preset')) === 'novelai' && (await nai.getAttribute('data-open')) === '', '添加 NovelAI：进 NovelAI 一节、展开')
check((await nai.getByTestId('ai-service-preset').count()) === 0 && (await nai.getByTestId('ai-service-nai-token').textContent()) === '使用 NAI 令牌', 'NovelAI 展开：没有「服务」下拉，API Key 写「使用 NAI 令牌」')
check((await page.getByTestId('ai-nai-none').count()) === 0, '加了以后「未添加」那一行没了')
await page.mouse.move(2, 890)
await page.waitForTimeout(300)
await shot(page.getByTestId('ai-services-nai'), 'nai-section')

await page.setViewportSize({ width: 760, height: 900 })
await page.waitForTimeout(300)
await svc.first().getByTestId('ai-service-head').click()
await page.waitForTimeout(300)
const over = await page.evaluate(() => {
  const g = document.querySelector('[data-testid=ai-settings]').getBoundingClientRect()
  return [...document.querySelectorAll('[data-testid=ai-settings] *')]
    .filter((el) => el.getBoundingClientRect().right > g.right + 1)
    .map((el) => `${el.tagName.toLowerCase()}[${el.getAttribute('data-testid') ?? ''}]`)
})
check(over.length === 0, `窄窗口没有溢出（${over.join(' / ')}）`)

console.log(errors.length ? `console errors: ${errors.join(' | ')}` : 'console errors: none')
if (errors.length) fails.push('console errors')
await browser.close()
await fake.close()
console.log(fails.length ? `FAILED: ${fails.join('; ')}` : 'all ok')
process.exit(fails.length ? 1 : 0)
