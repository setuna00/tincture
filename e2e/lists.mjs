const lists = () => page.evaluate(async () => JSON.parse((await window.__peImport('/src/store/storage.ts')).safeStorage.getItem('pe:lists') ?? '{"state":{"lists":[]}}').state.lists)
const nodeTags = async (title) => {
  const all = await lists()
  let found = null
  const walk = (ns) => ns.forEach((n) => (n.title === title && !found ? (found = n.tags) : walk(n.children)))
  all.forEach((l) => walk(l.nodes))
  return found
}
/** Radix restores trigger focus after its exit animation; filling another input sooner causes it to blur. */
