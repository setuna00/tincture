import { chromium } from '@playwright/test'
import { mkdirSync } from 'node:fs'
import os from 'node:os'
import path from 'node:path'
import { E2E_URL, isolate, resetStore, settled, stored } from './store.mjs'

const theme = process.argv[2] ?? 'light'
const out = 'e2e/shots'
mkdirSync(out, { recursive: true })
const browser = await chromium.launch()
const context = await browser.newContext({ viewport: { width: 1440, height: 900 }, deviceScaleFactor: 1 })
await isolate(context)
await context.route(/novelai\.net/, (r) => r.abort())
const errors = []
const watch = (p) => {
  p.on('console', (m) => m.type() === 'error' && !/Failed to load resource|novelai\.net/.test(m.text()) && errors.push(m.text()))
  p.on('pageerror', (e) => errors.push(String(e)))
}
let page = await context.newPage()
watch(page)
const fails = []
const check = (ok, msg) => (ok ? console.log('ok  ', msg) : (fails.push(msg), console.log('FAIL', msg)))
const ready = (p = page) => p.getByTestId('status-bar').waitFor({ timeout: 30000 })
const title = (p = page) => p.getByTestId('doc-title').inputValue()
const toasts = (p = page) => p.locator('[data-sonner-toast]').allInnerTexts()

await page.goto(E2E_URL)
await ready()
await resetStore(page, { theme })
await page.reload()
await ready()

await page.getByTestId('doc-title').fill('刷新前一刻改的')
await page.getByTestId('doc-title').press('Enter')
await page.reload()
await ready()
check((await title()) === '刷新前一刻改的', `改完马上刷新，标题还在（${await title()}）`)
await page.keyboard.press('Control+s')
await page.getByTestId('new-tab').click()
await page.getByTestId('start-new').click()
await page.waitForTimeout(200)
const tabsBefore = await page.getByTestId('tab').count()
await settled(page)
await page.reload()
await ready()
check((await page.getByTestId('tab').count()) === tabsBefore, `刷新后 tab 数照旧（${tabsBefore}）`)
check(JSON.parse(await stored(page, 'pe:library')).state.docs.some((d) => d.title === '刷新前一刻改的'), '「我的文档」里有刚保存的')
check(!(await page.evaluate(() => localStorage.getItem('pe:library'))), 'localStorage 里没有 pe:library（在图库文件夹里）')

const second = await context.newPage()
watch(second)
await second.goto(E2E_URL)
await second.getByTestId('other-tab').waitFor()
check((await second.getByTestId('other-tab').innerText()).includes('已在另一个浏览器标签页中打开'), '后开的标签页：「已在另一个浏览器标签页中打开」')
await page.getByTestId('tab').first().click()
await page.getByTestId('doc-title').fill('关掉前最后写的')
await page.getByTestId('doc-title').press('Enter')
await page.close()
page = second
await ready()
await page.getByTestId('other-tab').waitFor({ state: 'detached' })
check((await title()) === '关掉前最后写的', `前一个关掉后自动加载，读到它最后写的（${await title()}）`)

await page.route('**/api/bootstrap', (r) => r.abort())
await page.reload()
await page.getByTestId('boot-error').waitFor()
check((await page.getByTestId('boot-error').innerText()).includes('无法连接本地服务'), '连不上：「无法连接本地服务」')
await page.unroute('**/api/bootstrap')
await ready()
await page.getByTestId('boot-error').waitFor({ state: 'detached' })
check((await title()) === '关掉前最后写的', '本地服务好了以后自己加载，数据都在')

await page.route('**/api/kv', (r) => (r.request().method() === 'PUT' ? r.fulfill({ status: 500, body: '{"message":"disk full"}' }) : r.continue()))
await page.getByTestId('doc-title').fill('写失败时改的')
await page.getByTestId('doc-title').press('Enter')
await page.waitForTimeout(800)
const failToast = (await toasts()).find((t) => t.includes('无法写入图库文件夹'))
check(!!failToast && failToast.includes('更改尚未保存，将自动重试'), `写失败：「无法写入图库文件夹」·「更改尚未保存，将自动重试」（${failToast?.replace(/\n/g, ' · ')}）`)
await page.screenshot({ path: `${out}/storage-write-failed-${theme}.png`, clip: { x: 900, y: 600, width: 540, height: 300 } })
await page.unroute('**/api/kv')
await page.waitForFunction(() => ![...document.querySelectorAll('[data-sonner-toast]')].some((t) => t.textContent.includes('无法写入图库文件夹')), null, { timeout: 15000 })
check(true, '重试成功后提示消失')
await page.reload()
await ready()
check((await title()) === '写失败时改的', '重试写进去了，刷新还在')

await resetStore(page, { seed: null })
// Seed browser storage on a static same-origin page so the app cannot migrate partially written fixtures.
const docJson = await page.evaluate(async () => {
  const { blankDoc } = await import('/src/store/sample.ts')
  const { parsePrompt, toChip } = await import('/src/lib/nai.ts')
  const doc = blankDoc('浏览器里的老文档')
  doc.base.prompt[0].chips = parsePrompt('1girl, frieren, rain').map((c, i) => ({ ...toChip(c), id: `c${i}` }))
  return JSON.stringify(doc)
})
await page.goto(`${E2E_URL}favicon.svg`)
await page.evaluate(
  async ({ docJson, theme }) => {
    localStorage.setItem('pe:tabs', JSON.stringify({ state: { order: ['t_old'], activeId: 't_old', starts: [], links: {} }, version: 0 }))
    localStorage.setItem('pe:doc:t_old', docJson)
    localStorage.setItem('pe:prefs', JSON.stringify({ state: { theme }, version: 0 }))
    const db = await new Promise((resolve, reject) => {
      const r = indexedDB.open('keyval-store')
      r.onupgradeneeded = () => r.result.createObjectStore('keyval')
      r.onsuccess = () => resolve(r.result)
      r.onerror = () => reject(r.error)
    })
    const c = new OffscreenCanvas(83, 121)
    const g = c.getContext('2d')
    g.fillStyle = 'hsl(200 60% 50%)'
    g.fillRect(0, 0, 83, 121)
    const blob = await c.convertToBlob({ type: 'image/webp' })
    const doc = JSON.parse(docJson)
    const tx = db.transaction('keyval', 'readwrite')
    const store = tx.objectStore('keyval')
    for (let i = 0; i < 12; i++)
      store.put({ id: `img_old${i}`, tabId: 't_old', batch: `b${i >> 2}`, index: i % 4, createdAt: Date.UTC(2026, 9, 1) + i, seed: i, width: 832, height: 1216, model: 'nai-diffusion-5-full', blob, doc }, `gen:t_old:img_old${i}`)
    store.put(blob, 'tpl-img:old1')
    await new Promise((r) => (tx.oncomplete = r))
    db.close()
  },
  { docJson, theme },
)
const before = await page.evaluate(() => Object.keys(localStorage).sort())
await page.goto(E2E_URL)
await ready()
const migToast = await page.locator('[data-sonner-toast]', { hasText: '已将数据移至图库文件夹' }).waitFor({ timeout: 5000 }).then(() => true, () => false)
check(migToast, 'toast「已将数据移至图库文件夹」')
check((await title()) === '浏览器里的老文档', `老文档搬过来了（${await title()}）`)
const libImages = await page.evaluate(async () => (await (await window.__peImport('/src/store/storage.ts')).imageStore.list()).length)
check(libImages === 12, `12 张图搬进图库文件夹（${libImages}）`)
const tplOk = await page.evaluate(async () => !!(await (await window.__peImport('/src/store/storage.ts')).assetStore.get('tpl-img:old1')))
check(tplOk, '模板配图搬过来了')
const after = await page.evaluate(() => Object.keys(localStorage).sort())
check(before.every((k) => after.includes(k)) && after.includes('pe:migrated'), `浏览器里的老数据没删，多了 pe:migrated（${after.join(' ')}）`)
const idbLeft = await page.evaluate(async () => (await (await window.__peImport('/src/store/storage.ts')).assetStore.getMany(['gen:t_old:img_old0'])).filter(Boolean).length)
check(idbLeft === 1, 'IndexedDB 里的老图没删')
await page.getByTestId('page-gallery').click()
await page.locator('[data-testid=gallery-cell], [data-testid=gallery-stack]').first().waitFor()
check((await page.getByTestId('gallery-count').innerText()).includes('12'), '图库页 12 张（从图库文件夹读）')
await page.reload()
await ready()
check(!(await toasts()).some((t) => t.includes('已将数据移至图库文件夹')), '再刷新不重复搬')

await page.goto(`${E2E_URL}#/settings`)
await page.getByTestId('settings-nav-library').click()
await page.getByTestId('library-settings').waitFor()
const dir0 = await page.getByTestId('library-dir').innerText()
check(dir0.length > 3 && !dir0.includes('Documents') && !dir0.includes('文档'), `显示图库文件夹（测试用临时目录：${dir0}）`)
check((await page.locator('[data-testid=settings-nav-library]').innerText()) === '图库', '目录里有「图库」')
const reveal = page.waitForResponse((r) => r.url().includes('/api/library/reveal'))
await page.getByTestId('library-reveal').click()
check((await reveal).ok(), '在资源管理器中打开（测试模式不真的弹）')
await page.getByTestId('library-change').click()
await page.getByTestId('library-input').waitFor()
check((await page.getByTestId('library-input').inputValue()) === dir0, '更换：输入框填好当前路径')
await page.getByTestId('library-input').fill('relative\\dir')
await page.getByTestId('library-apply').click()
await page.waitForTimeout(300)
check((await page.getByTestId('library-hint').innerText()) === '请输入完整路径', `相对路径：红字「请输入完整路径」（${await page.getByTestId('library-hint').innerText()}）`)
const nowhere = path.join(os.tmpdir(), `pe-e2e-nope-${Date.now()}`, 'x')
await page.getByTestId('library-input').fill(nowhere)
await page.getByTestId('library-apply').click()
await page.waitForTimeout(300)
check((await page.getByTestId('library-hint').innerText()) === '上级文件夹不存在', '上级不存在：「上级文件夹不存在」')
await page.keyboard.press('Escape')
await page.waitForTimeout(300)
check((await page.getByTestId('library-edit').getAttribute('data-open')) === null, 'Esc 收起')
const other = path.join(os.tmpdir(), `pe-e2e-other-${Date.now()}`)
await page.getByTestId('library-change').click()
await page.getByTestId('library-input').fill(other)
await Promise.all([page.waitForEvent('load'), page.getByTestId('library-apply').click()])
await ready()
await page.getByTestId('settings-nav-library').click()
await page.getByTestId('library-settings').waitFor()
check((await page.getByTestId('library-dir').innerText()) === other, `换到新文件夹并重新载入（${await page.getByTestId('library-dir').innerText()}）`)
check(!(await toasts()).some((t) => t.includes('已将数据移至图库文件夹')), '换到空文件夹：不复制、不再迁移')
await page.getByTestId('page-gallery').click()
await page.getByTestId('gallery-empty').waitFor()
check(true, '新图库是空的')
await page.goto(`${E2E_URL}#/settings`)
await page.getByTestId('settings-nav-library').click()
await page.getByTestId('library-change').click()
await page.getByTestId('library-input').fill(dir0)
await Promise.all([page.waitForEvent('load'), page.getByTestId('library-apply').click()])
await ready()
await page.getByTestId('page-gallery').click()
await page.locator('[data-testid=gallery-cell], [data-testid=gallery-stack]').first().waitFor()
check((await page.getByTestId('gallery-count').innerText()).includes('12'), '换回原来的文件夹：12 张图都在')

console.log(errors.length ? `console 报错：\n${errors.join('\n')}` : 'console 无报错')
if (errors.length) fails.push('console 报错')
console.log(fails.length ? `\n${fails.length} 项失败` : '\n全部通过')
await browser.close()
process.exit(fails.length ? 1 : 0)
