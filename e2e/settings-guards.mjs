import { chromium } from '@playwright/test'
import { E2E_URL, isolate, resetStore } from './store.mjs'

const theme = process.argv[2] ?? 'light'
const browser = await chromium.launch()
const context = await browser.newContext({ viewport: { width: 1440, height: 900 } })
await isolate(context)
await context.route(/novelai\.net|deepseek\.com|openai\.com|anthropic\.com/, (r) => r.abort())
const page = await context.newPage()
const errors = []
page.on('console', (m) => m.type() === 'error' && !/Failed to load resource|deepseek|openai|novelai/.test(m.text()) && errors.push(m.text()))
page.on('pageerror', (e) => errors.push(String(e)))
const fails = []
const check = (ok, msg) => (ok ? console.log('ok  ', msg) : (fails.push(msg), console.log('FAIL', msg)))
const tid = (id) => page.getByTestId(id)

await page.goto(E2E_URL)
await resetStore(page, { theme })
await page.reload()
await page.waitForSelector('[data-testid=app-rail]', { timeout: 60000 })
await page.evaluate(() => (location.hash = '#/settings'))
await page.waitForSelector('[data-testid=settings-page]')
const setRunning = (on) => page.evaluate(async (on) => (await window.__peImport('/src/store/gen.ts')).useGen.setState({ running: on ? { tabId: 'x', docId: 'x', progress: 0.3 } : null }), on)

await tid('settings-nav-library').click()
await tid('library-change').click()
await page.waitForTimeout(300)
check(await tid('library-apply').isDisabled(), '路径没改：「使用此文件夹」不能点')
check((await tid('library-hint').innerText()).includes('当前内容留在原文件夹，不复制'), `灰字：「…当前内容留在原文件夹，不复制」（${await tid('library-hint').innerText()}）`)
await tid('library-apply').hover({ force: true })
await page.waitForTimeout(800)
check((await page.locator('[data-slot=tooltip-content]').first().innerText()).includes('与当前图库文件夹相同'), '路径没改：悬停写「与当前图库文件夹相同」')
await page.mouse.move(5, 5)
await page.waitForTimeout(300)
await tid('library-input').fill('E:/Other Library')
check(!(await tid('library-apply').isDisabled()), '改了路径：能点')
await setRunning(true)
await page.waitForTimeout(150)
check(await tid('library-apply').isDisabled(), '图片生成中：不能点')
await tid('library-apply').hover({ force: true })
await page.waitForTimeout(800)
check((await page.locator('[data-slot=tooltip-content]').first().innerText()).includes('图片生成中，无法更换图库文件夹'), '悬停写「图片生成中，无法更换图库文件夹」')
await tid('library-input').press('Enter')
await page.waitForTimeout(300)
check((await page.evaluate(() => location.hash)) === '#/settings' && (await tid('library-input').count()) === 1, '图片生成中按 ↵ 也不换（没有重新载入）')
await setRunning(false)
await page.waitForTimeout(150)
check(!(await tid('library-apply').isDisabled()), '生成结束：又能点')
await tid('library-cancel').click()

await tid('settings-nav-ai').click()
await tid('ai-add-service').click()
await page.waitForTimeout(400)
const preset = async () => (await tid('ai-service-preset').innerText()).trim()
const p0 = await preset()
const stored = () => page.evaluate(async () => (await window.__peImport('/src/store/ai.ts')).useAi.getState().services.map((s) => ({ preset: s.preset, key: s.key })))
await tid('ai-service-preset').click()
await page.getByRole('option', { name: 'OpenAI', exact: true }).click()
await page.waitForTimeout(400)
check((await page.locator('[data-sonner-toast]').count()) === 0, '还没填 key 时换预设：不提示')
await tid('ai-service-preset').click()
await page.getByRole('option', { name: p0, exact: true }).click()
await page.waitForTimeout(300)
await tid('ai-service-key').fill('sk-test-1234567890')
await page.waitForTimeout(100)
await tid('ai-service-preset').click()
await page.getByRole('option', { name: 'OpenAI', exact: true }).click()
await page.waitForTimeout(400)
const toastEl = page.locator('[data-sonner-toast]').filter({ hasText: '已清空 API Key' })
check((await toastEl.count()) === 1 && (await tid('ai-service-key').inputValue()) === '', '填了 key 换预设：key 清空，toast「已清空 API Key」')
await toastEl.getByRole('button', { name: '撤销' }).click()
await page.waitForTimeout(400)
const after = await stored()
check((await preset()) === p0 && (await tid('ai-service-key').inputValue()) === 'sk-test-1234567890' && after[0]?.preset !== 'openai' && after[0]?.key === 'sk-test-1234567890', `撤销：回到 ${p0}，key 回来（${JSON.stringify(after)}）`)

console.log(fails.length ? `\n${fails.length} FAIL` : '\nall ok', 'errors', errors.length ? errors : 'none')
await browser.close()
process.exit(fails.length ? 1 : 0)
