import { chromium } from '@playwright/test'
import { E2E_URL, isolate, resetStore } from './store.mjs'

const theme = process.argv[2] ?? 'light'
const browser = await chromium.launch()
const context = await browser.newContext({ viewport: { width: 1440, height: 900 }, deviceScaleFactor: 1 })
await isolate(context)
await context.route(/novelai\.net/, (r) => r.abort())
const page = await context.newPage()
const errors = []
page.on('console', (m) => m.type() === 'error' && !/404|novelai\.net|Failed to load resource/.test(m.text()) && errors.push(m.text()))
page.on('pageerror', (e) => errors.push(String(e)))
const fails = []
const check = (ok, msg) => (ok ? console.log('ok  ', msg) : (fails.push(msg), console.log('FAIL', msg)))
const T = (id) => page.getByTestId(id)
const doc = () =>
  page.evaluate(async () => {
    const t = await window.__peImport('/src/store/tabs.ts')
    return t.getDocStore(t.useTabs.getState().activeId).getState().doc
  })
const weights = async () => JSON.stringify((await doc()).base.prompt.map((s) => s.chips.map((c) => c.weight)))
const imeEnter = (loc) => loc.evaluate((el) => el.dispatchEvent(new KeyboardEvent('keydown', { key: 'Enter', isComposing: true, bubbles: true, cancelable: true })))

await page.goto(E2E_URL)
await resetStore(page, { theme })
await page.reload()
await T('status-bar').waitFor()

console.log('1. tag 权重')
await T('chip').first().click()
const w = T('inspector-weight-input')
await w.waitFor()
const w0 = await weights()
const shown0 = await w.inputValue()
await w.click()
await page.keyboard.type('1.7')
await page.keyboard.press('Escape')
await page.waitForTimeout(150)
check((await weights()) === w0, 'tag 权重框打 1.7 再按 Esc：权重没变')
await w.click()
await page.keyboard.type('1.3')
await imeEnter(w)
await page.waitForTimeout(150)
check((await weights()) === w0 && (await w.inputValue()) === '1.3', '组字时的 ↵：不提交，框里还是打的字')
await page.keyboard.press('Enter')
await page.waitForTimeout(150)
check((await doc()).base.prompt[0].chips[0].weight === 1.3, `再按 ↵ 才提交：1.3（${shown0} → ${await w.inputValue()}）`)
await page.keyboard.press('Control+z')
await page.waitForTimeout(150)

console.log('2. 多选')
await T('chip').nth(1).click({ modifiers: ['Control'] })
const m = T('multi-weight-input')
await m.waitFor()
const m0 = await weights()
await m.click()
await page.keyboard.type('1.7')
await page.keyboard.press('Escape')
await page.waitForTimeout(150)
check((await weights()) === m0, '多选「全部设成」打 1.7 再按 Esc：选中的都没变')
await page.locator('[data-testid=board]').click({ position: { x: 5, y: 5 } }).catch(() => {})
await page.keyboard.press('Escape')
await page.keyboard.press('Escape')

console.log('3. 参数面板')
const width0 = (await doc()).settings.gen.width
await T('params-button').click()
await T('set-width').waitFor()
await T('set-width').click()
await page.keyboard.press('Control+a')
await page.keyboard.type('640')
await page.keyboard.press('Escape')
await page.waitForTimeout(400)
check((await doc()).settings.gen.width === width0, `宽打 640 再按 Esc：没变（${(await doc()).settings.gen.width}）`)
check((await T('params-panel').count()) === 0, 'Esc：参数面板收起（焦点在面板里）')

console.log('4. tab 改名')
await T('tab').first().click({ button: 'right' })
await T('tab-menu-rename').click()
const r = T('tab-rename')
await r.waitFor()
await page.keyboard.press('Control+a')
await page.keyboard.type('  雨夜  ')
await imeEnter(r)
await page.waitForTimeout(150)
check((await r.count()) === 1, '组字时的 ↵：还在改名')
await page.keyboard.press('Enter')
await page.waitForTimeout(200)
check((await doc()).meta.title === '雨夜', `↵ 提交，去掉首尾空格（「${(await doc()).meta.title}」）`)
await T('tab').first().click({ button: 'right' })
await T('tab-menu-rename').click()
await r.waitFor()
await page.keyboard.press('Control+a')
await page.keyboard.type('晴天')
await page.keyboard.press('Escape')
await page.waitForTimeout(200)
check((await r.count()) === 0 && (await doc()).meta.title === '雨夜', 'Esc：不改名')

check(!errors.length, `没有报错${errors.length ? `：${errors.slice(0, 3).join(' | ')}` : ''}`)
await browser.close()
console.log(fails.length ? `\n${fails.length} FAIL` : '\nall ok')
process.exit(fails.length ? 1 : 0)
