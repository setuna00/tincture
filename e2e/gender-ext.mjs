import { chromium } from '@playwright/test'
import { mkdirSync } from 'node:fs'
import { E2E_URL, isolate, resetStore } from './store.mjs'

const theme = process.argv[2] ?? 'light'
const prefix = process.argv[3] ?? 'r48'
const W = Number(process.argv[4] ?? 1440)
const H = 900
const out = 'e2e/shots'
mkdirSync(out, { recursive: true })

const browser = await chromium.launch()
const page = await browser.newPage({ viewport: { width: W, height: H }, deviceScaleFactor: 2 })
await isolate(page.context())
const errors = []
page.on('console', (m) => m.type() === 'error' && errors.push(m.text()))
page.on('pageerror', (e) => errors.push(String(e)))
const base = E2E_URL
await page.goto(base)
await resetStore(page, { theme })
await page.reload()
await page.getByTestId('chip').first().waitFor()
const hideToasts = () => page.addStyleTag({ content: '[data-sonner-toaster]{visibility:hidden}' })
let toastStyle = await hideToasts()
await page.waitForTimeout(300)

let fails = 0
const check = (ok, what) => {
  if (!ok) fails++
  console.log(ok ? '  ✓' : '  ✗', what)
}
const suffix = `${theme}${W === 1440 ? '' : `-${W}`}`
const shot = async (name, loc) => {
  await page.mouse.move(2, H - 4)
  await page.waitForTimeout(350)
  const file = `${out}/${prefix}-${name}-${suffix}.png`
  if (loc) await loc.screenshot({ path: file })
  else await page.screenshot({ path: file })
  console.log('shot', file)
}
const prefs = () => page.evaluate(async () => JSON.parse((await window.__peImport('/src/store/storage.ts')).safeStorage.getItem('pe:prefs') ?? '{}').state ?? {})
const checked = async (id) => (await page.getByTestId(id).getAttribute('aria-checked')) === 'true'
const stark = () => page.locator('[data-testid=character][data-g=male]').first()
const exportText = (i) => page.locator('[data-testid=export-char]').nth(i).locator('.x-out').first().innerText()
const lastCharExport = () => page.locator('[data-testid=export-char]').last().locator('.x-out').first().innerText()
const settings = async () => {
  await page.getByTestId('rail-settings').click()
  await page.getByTestId('settings-nav-content').click()
  await page.getByTestId('app-settings').waitFor()
}
const editor = async () => {
  await page.getByTestId('page-editor').click()
  await page.getByTestId('chip').first().waitFor()
}

console.log('1. 设置页：NSFW 两个开关')
await settings()
check(!(await checked('set-nsfw')), 'NSFW 默认关')
check(await page.getByTestId('set-r18g').isDisabled(), 'NSFW 关着：R18G 点不了')
check((await page.getByTestId('set-r18g-row').getAttribute('data-off')) !== null, 'NSFW 关着：R18G 那行变淡')
await page.getByTestId('set-nsfw').click()
check((await prefs()).nsfw === 'r18', '打开 NSFW = R18')
check(!(await page.getByTestId('set-r18g').isDisabled()), 'NSFW 开着：R18G 能点')
await page.getByTestId('set-r18g').click()
check((await prefs()).nsfw === 'r18g', '再打开 R18G = R18 + R18G')
await page.getByTestId('set-nsfw').click()
check((await prefs()).nsfw === 'off' && (await checked('set-r18g')), '关掉 NSFW：生效的是关，R18G 开关记着「开」')
await page.getByTestId('set-nsfw').click()
check((await prefs()).nsfw === 'r18g', '再打开 NSFW：R18G 照它恢复')
await page.getByTestId('set-r18g').click()
check((await prefs()).nsfw === 'r18', '关掉 R18G：回到 R18')

console.log('2. 更多性别：默认关；打开后预设各有开关，R18 的跟着 NSFW')
check(!(await checked('set-more-genders')), '更多性别默认关')
check((await page.getByTestId('gender-list-wrap').getAttribute('data-open')) === null, '关着：列表收起')
await editor()
await page.getByTestId('add-character').click()
check((await page.locator('[data-testid^=add-character-ext-]').count()) === 0, '关着：添加角色菜单只有 女 / 男 / 其他')
await page.keyboard.press('Escape')
await settings()
await page.getByTestId('set-more-genders').click()
await page.waitForTimeout(300)
const presetNames = () => page.getByTestId('gender-preset').evaluateAll((els) => els.map((e) => e.dataset.id))
check((await presetNames()).length === 7, `NSFW 开着：7 个预设（${(await presetNames()).join(' / ')}）`)
await page.getByTestId('set-nsfw').click()
await page.waitForTimeout(100)
const off5 = await presetNames()
check(off5.length === 5 && !off5.includes('futanari') && !off5.includes('cuntboy'), `NSFW 关着：不列扶她、有阴道的男性（${off5.length} 个）`)
await page.getByTestId('set-nsfw').click()
await page.locator('[data-testid=gender-preset][data-id=reverse-trap]').getByTestId('gender-preset-switch').click()
check((await prefs()).genderPresetsOff?.includes('reverse-trap'), '关掉「男装女子」')

console.log('3. 自己加一个：名字 · NAI 性别 · tag')
await page.getByTestId('add-custom-gender').click()
await page.waitForTimeout(300)
const custom = page.getByTestId('gender-custom').last()
check((await custom.getAttribute('data-open')) !== null, '新加的展开着')
check(await page.getByTestId('gender-custom-name').evaluate((el) => el === document.activeElement), '焦点在名字框')
await page.getByTestId('gender-custom-name').fill('女装少年')
await custom.getByTestId('gender-custom-base-male').click()
const tagInput = custom.getByTestId('gender-custom-tag-input')
await tagInput.click()
await tagInput.pressSequentially('otoko no k')
await page.waitForTimeout(600)
await tagInput.press('Enter')
await page.waitForTimeout(200)
await tagInput.fill('crossdressing (mtf)')
await page.waitForTimeout(600)
await tagInput.press('Enter')
await page.waitForTimeout(200)
const tags = await custom.getByTestId('gender-custom-tag').evaluateAll((els) => els.map((e) => e.dataset.tag))
check(JSON.stringify(tags) === JSON.stringify(['otoko no ko', 'crossdressing (mtf)']), `补全加了两个 tag（${tags.join(' / ')}）`)
await shot('settings-custom', page.locator('section').first())
await custom.getByTestId('gender-custom-head').click()
await page.waitForTimeout(300)
check((await custom.getByTestId('gender-custom-head').innerText()).includes('boy, otoko no ko, crossdressing (mtf)'), '收起后一行：导出时添加的 tag')
await shot('settings', page.locator('section').first())

console.log('4. 编辑器：添加角色菜单')
await editor()
const nChars = await page.getByTestId('character').count()
await page.getByTestId('add-character').click()
await page.waitForTimeout(250)
const menuItems = await page.locator('[data-testid^=add-character-ext-]').evaluateAll((els) => els.map((e) => e.dataset.testid.slice('add-character-ext-'.length)))
check(
  JSON.stringify(menuItems) === JSON.stringify(['女体化', '扶她', '男体化', '伪娘', '有阴道的男性', '性别不明', '女装少年']),
  `菜单：开着的预设 + 自己加的（${menuItems.join(' / ')}）`,
)
await shot('menu', page.locator('[role=menu]'))
await page.getByTestId('add-character-ext-女装少年').click()
await page.waitForTimeout(300)
check((await page.getByTestId('character').count()) === nChars + 1, '添加了一个角色')
check((await page.getByTestId('character').last().getByTestId('gender-name').innerText()) === '女装少年', '新角色头部：图标后面写「女装少年」')
check((await lastCharExport()).startsWith('boy, otoko no ko, crossdressing (mtf)'), `导出：${(await lastCharExport()).slice(0, 40)}`)

console.log('5. 头部菜单换扩展性别 + 撤销；左栏按钮')
await page.keyboard.press('Escape')
await page.keyboard.press('Escape')
await stark().scrollIntoViewIfNeeded()
await stark().getByTestId('character-gender').click()
await page.waitForTimeout(250)
check((await page.locator('[role=menuitemradio][data-testid=gender-male]').getAttribute('aria-checked')) === 'true', '修塔尔克的菜单：男勾着')
await page.getByTestId('gender-ext-男体化').click()
await page.waitForTimeout(300)
check((await stark().getByTestId('gender-name').innerText()) === '男体化', '头部写「男体化」')
check((await exportText(2)).startsWith('boy, genderswap (ftm), stark'), `导出：${(await exportText(2)).slice(0, 34)}`)
await page.keyboard.press('Control+z')
await page.waitForTimeout(200)
check((await stark().getByTestId('gender-name').count()) === 0, 'Ctrl+Z：回到普通的男（没有名字）')
check((await exportText(2)).startsWith('boy, stark'), '导出回到 boy, stark')
const headBox = await stark().locator('.char-head').boundingBox()
await stark().locator('.char-head').click({ position: { x: headBox.width * 0.62, y: 14 } })
await page.getByTestId('character-inspector-gender').click()
await page.waitForTimeout(250)
await page.getByTestId('gender-ext-伪娘').click()
await page.waitForTimeout(300)
check((await page.getByTestId('character-inspector-gender').innerText()).includes('伪娘'), '左栏按钮写「伪娘」')
check((await page.getByTestId('character-inspector-gender-hint').innerText()).includes('boy, otoko no ko'), '左栏下面一行：添加 boy, otoko no ko')
check((await stark().getByTestId('gender-name').innerText()) === '伪娘', '头部跟着变')
await shot('head', stark().locator('.char-head'))
await shot('inspector', page.getByTestId('character-inspector'))
const xg = page.locator('[data-testid=export-char]').nth(2)
await xg.scrollIntoViewIfNeeded()
check((await xg.locator('[data-testid=export-gender]').count()) === 2, '导出栏：boy、otoko no ko 都是性别色')
await shot('export', xg)

console.log('6. 关掉更多性别：已有的角色不变，菜单里照样列出它（勾着）')
await settings()
await page.getByTestId('set-more-genders').click()
await editor()
check((await stark().getByTestId('gender-name').innerText()) === '伪娘', '修塔尔克还是伪娘')
check((await exportText(2)).startsWith('boy, otoko no ko'), '导出照旧带 otoko no ko')
await stark().getByTestId('character-gender').click()
await page.waitForTimeout(250)
const radios = await page.locator('[role=menuitemradio]').evaluateAll((els) => els.map((e) => `${e.dataset.testid}:${e.getAttribute('aria-checked')}`))
check(JSON.stringify(radios) === JSON.stringify(['gender-female:false', 'gender-male:false', 'gender-other:false', 'gender-ext-伪娘:true']), `菜单：女 / 男 / 其他 + 现在的伪娘（${radios.join(' ')}）`)
await page.keyboard.press('Escape')

console.log('7. 删除自己加的 + 撤销')
await settings()
await page.getByTestId('set-more-genders').click()
await page.waitForTimeout(300)
await page.getByTestId('gender-custom-head').last().click()
await page.waitForTimeout(250)
await page.getByTestId('gender-custom-delete').click()
check((await page.getByTestId('gender-custom').count()) === 0, '删除')
await toastStyle.evaluate((el) => el.remove())
await page.locator('[data-sonner-toast]').last().getByRole('button', { name: '撤销' }).click()
toastStyle = await hideToasts()
check((await page.getByTestId('gender-custom').count()) === 1, '撤销：回来了')

console.log('8. 角色随机：性别选项多了开着的扩展性别')
await editor()
await page.keyboard.press('Escape')
const randomRows = page.getByTestId('random-row')
if (!(await randomRows.count())) await page.locator('[data-testid=lib-folder][data-folder=random]').click()
await randomRows.first().waitFor()
const nBefore = await page.getByTestId('character').count()
const rb = await randomRows.first().boundingBox()
const eb = await page.getByTestId('editor-scroll').boundingBox()
await page.mouse.move(rb.x + 50, rb.y + rb.height / 2)
await page.mouse.down()
await page.mouse.move(rb.x + 70, rb.y + 20, { steps: 4 })
await page.mouse.move(eb.x + eb.width / 2, eb.y + 300, { steps: 14 })
await page.waitForTimeout(200)
await page.mouse.up()
await page.waitForTimeout(900)
check((await page.getByTestId('character').count()) === nBefore + 1, '拖「角色随机」进编辑区：多一个角色框')
const rch = page.getByTestId('character').last()
await rch.scrollIntoViewIfNeeded()
await rch.getByTestId('section').first().locator('.section-head').click({ position: { x: 160, y: 8 } })
await page.getByTestId('random-genders').waitFor()
const picks = await page.getByTestId('random-genders').locator('button').evaluateAll((els) => els.map((e) => e.dataset.testid.slice('random-genders-'.length)))
check(picks.slice(0, 4).join() === 'canon,female,male,other' && picks.includes('伪娘'), `性别选项：原作 / 女 / 男 / 其他 + 开着的扩展性别（${picks.join(', ')}）`)
await page.getByTestId('random-genders-伪娘').click()
await page.getByTestId('random-genders-canon').click()
await page.waitForTimeout(300)
check((await rch.locator('[data-testid=gender-name]').innerText()) === '伪娘', '只勾伪娘：框头写伪娘')
check((await lastCharExport()).startsWith('boy, otoko no ko'), `导出带上伪娘的 tag（${(await lastCharExport()).slice(0, 40)}）`)
await shot('random-genders', page.getByTestId('random-genders'))

check(errors.length === 0, `控制台没有报错${errors.length ? `：${errors.slice(0, 3).join(' | ')}` : ''}`)
await browser.close()
console.log(fails ? `\n${fails} 处没过` : '\n全部通过')
process.exit(fails ? 1 : 0)
