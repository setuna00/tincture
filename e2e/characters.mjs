check((await exportText(0)).startsWith('girl, frieren'), `导出：${(await exportText(0)).slice(0, 30)}`)
check((await exportText(2)).startsWith('boy, stark'), `导出：${(await exportText(2)).slice(0, 30)}`)
check((await page.getByTestId('export-gender').count()) === 3, '导出栏里 3 个自动加的性别词')
check((await page.getByTestId('chip').filter({ hasText: /^girl/ }).count()) === 0, '区块里没有 girl chip')
await scrollChars()
