import { chromium } from '@playwright/test'
import { mkdirSync } from 'node:fs'
import { E2E_URL, isolate, resetStore } from './store.mjs'

const theme = process.argv[2] ?? 'light'
const prefix = process.argv[3] ?? 'r23'
const W = Number(process.argv[4] ?? 1440)
const out = 'e2e/shots'
mkdirSync(out, { recursive: true })

const browser = await chromium.launch()
const page = await browser.newPage({ viewport: { width: W, height: 900 }, deviceScaleFactor: 2 })
await isolate(page.context())
const errors = []
page.on('console', (m) => m.type() === 'error' && errors.push(m.text()))
page.on('pageerror', (e) => errors.push(String(e)))
await page.goto(E2E_URL)
await resetStore(page, { theme })
await page.reload()
await page.waitForLoadState('networkidle')
await page.waitForTimeout(500)

let fails = 0
const check = (ok, what) => {
  if (!ok) fails++
  console.log(ok ? '  ✓' : '  ✗', what)
}
const shot = async (name, clip) => {
  await page.waitForTimeout(260)
  const file = `${out}/${prefix}-${name}-${theme}${W === 1440 ? '' : `-${W}`}.png`
  await page.screenshot({ path: file, ...(clip ? { clip } : {}) })
  console.log('shot', file)
}
const box = async (loc, pad = 10) => {
  const b = await loc.boundingBox()
  return { x: b.x - pad, y: b.y - pad, width: b.width + pad * 2, height: b.height + pad * 2 }
}
const chars = page.getByTestId('character')
const names = () => page.getByTestId('character-name').evaluateAll((els) => els.map((e) => e.value || e.placeholder))
const exportText = (i) => page.getByTestId('export-char').nth(i).getByTestId('export-text').first().innerText()
const scrollChars = async () => {
  await page.evaluate(() => document.querySelector('[data-testid=characters]').scrollIntoView({ block: 'start' }))
  await page.mouse.move(2, 890)
}

