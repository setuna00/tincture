// Radix restores trigger focus after its exit animation; delay typing to expose focus stolen from the newly opened input.
import { chromium } from '@playwright/test'
import { seed } from './gallery-seed.mjs'
import { GOOD_KEY, startFakeAi } from './fake-ai.mjs'
import { E2E_URL, isolate, resetStore } from './store.mjs'

const theme = process.argv[2] ?? 'light'
const base = E2E_URL
const fake = await startFakeAi()
const browser = await chromium.launch()
const context = await browser.newContext({ viewport: { width: 1440, height: 900 }, deviceScaleFactor: 1 })
await isolate(context)
await context.route(/novelai\.net/, (r) => r.abort())
await context.route('https://danbooru.donmai.us/**', (r) => r.fulfill({ status: 404, contentType: 'application/json', body: '{"success":false}' }))
const page = await context.newPage()
const errors = []
page.on('console', (m) => m.type() === 'error' && !/404|novelai\.net|Failed to load resource/.test(m.text()) && errors.push(m.text()))
page.on('pageerror', (e) => errors.push(String(e)))

const fails = []
const check = (ok, msg) => (ok ? console.log('ok  ', msg) : (fails.push(msg), console.log('FAIL', msg)))
const T = (id) => page.getByTestId(id)
const active = () => page.evaluate(() => document.activeElement?.getAttribute('data-testid') ?? document.activeElement?.tagName)
const pause = () => page.waitForTimeout(300)
const clean = async () => {
  for (let i = 0; i < 3 && (await page.locator('[role=menu], [role=dialog], [role=alertdialog]').count()); i++) {
    await page.keyboard.press('Escape')
    await page.waitForTimeout(250)
  }
}

await page.goto(base)
await resetStore(page, { theme, prefs: { galleryStack: false, discoverNode: { b: '外观/头发/发型' }, discoverOpen: { 'b:外观': true, 'b:外观/头发': true, 'b:外观/头发/发型': true } } })
await page.reload()
await T('status-bar').waitFor()

console.log('0. 编辑器')
const sec = T('section').first()
await sec.hover()
await sec.getByTestId('section-more').click()
await page.getByRole('menuitem', { name: '重命名' }).click()
await pause()
check((await active()) === 'section-name-input', `区块 ⋯ → 重命名，0.3 秒后名字框有焦点（${await active()}）`)
await page.keyboard.press('Escape')
await clean()
await sec.getByTestId('section-name').click({ button: 'right' })
await page.getByRole('menuitem', { name: '重命名' }).click()
await pause()
check((await active()) === 'section-name-input', `区块右键 → 重命名，0.3 秒后名字框有焦点（${await active()}）`)
await page.keyboard.press('Escape')
await clean()
await T('chip').first().click({ button: 'right' })
await page.getByRole('menuitem', { name: '编辑' }).click()
await pause()
check((await active()) === 'chip-edit', `chip 右键 → 编辑，0.3 秒后编辑框有焦点（${await active()}）`)
await page.keyboard.press('Escape')
await clean()
await T('tab').first().click({ button: 'right' })
await T('tab-menu-rename').click()
await pause()
check((await active()) === 'tab-rename', `tab 右键 → 重命名，0.3 秒后名字框有焦点（${await active()}）`)
await page.keyboard.press('Escape')
await clean()
await T('add-character').scrollIntoViewIfNeeded()
await T('add-character').click()
await T('add-character-library').click()
await pause()
check((await active()) === 'template-filter', `添加角色 → 从模板库选择，0.3 秒后焦点在库的搜索框（${await active()}）`)
await page.keyboard.press('Escape')
await clean()
await T('doc-title').click()
await page.keyboard.press('Control+s')
await page.waitForTimeout(300)
await T('new-tab').click()
await T('start-doc').first().click({ button: 'right' })
await T('start-doc-menu-rename').click()
await pause()
check((await active()) === 'start-doc-title-input', `开始页右键 → 重命名，0.3 秒后名字框有焦点（${await active()}）`)
await page.keyboard.press('Escape')
await clean()
await T('page-library').click()
await T('lib-item').first().waitFor()
await T('lib-item').first().click({ button: 'right' })
await T('lib-item-move').click()
await pause()
check((await T('lib-move-menu').count()) === 1 && (await active()) === 'lib-move-search', `模板管理页右键 → 移至目录，0.3 秒后列表开着、焦点在搜索框（${await active()}）`)
await page.keyboard.press('Escape')
await clean()

console.log('1. 发现页')
await T('page-discover').click()
await T('discover-row').first().waitFor()
await T('discover-list').click()
await page.locator('[data-testid=discover-list-item][data-name="樱花场景"]').click()
await page.waitForTimeout(300)
await T('discover-list-menu').click()
await T('discover-list-rename').click()
await pause()
check((await T('discover-list-rename-input').count()) === 1 && (await active()) === 'discover-list-rename-input', `list ⋯ → 重命名，0.3 秒后输入框还在、有焦点（${await active()}）`)
await page.keyboard.type('春')
await page.keyboard.press('Enter')
await page.waitForTimeout(200)
check((await T('discover-list').innerText()).includes('春'), 'list 改名打的字进去了')
await clean()

await T('discover-node-add').click()
await T('discover-node-rename-input').waitFor()
await page.keyboard.press('Enter')
const node = page.locator('[data-testid=discover-node][data-title="未命名"]').first()
await node.waitFor()
await node.click({ button: 'right' })
await T('discover-node-rename').click()
await pause()
check((await T('discover-node-rename-input').count()) === 1 && (await active()) === 'discover-node-rename-input', `节点右键 → 重命名，0.3 秒后输入框还在、有焦点（${await active()}）`)
await page.keyboard.press('Control+a')
await page.keyboard.type('雨天')
await page.keyboard.press('Enter')
await page.locator('[data-testid=discover-node][data-title="雨天"]').first().waitFor({ timeout: 2000 }).then(
  () => check(true, '节点改名打的字进去了'),
  () => check(false, '节点改名打的字进去了'),
)
await clean()
await T('discover-list-menu').click()
await T('discover-list-delete').click()
await pause()
check((await page.locator('[role=alertdialog]').count()) === 1 && (await page.evaluate(() => !!document.activeElement?.closest('[role=alertdialog]'))), `list ⋯ → 删除，0.3 秒后确认框开着、焦点在框里（${await active()}）`)
await page.keyboard.press('Escape')
await page.waitForTimeout(300)
check((await page.locator('[role=alertdialog]').count()) === 0 && (await T('discover-list').innerText()).includes('春'), 'Esc 取消：list 还在')
await clean()
await T('discover-list').click()
await T('discover-list-b').click()
await page.waitForTimeout(300)
await page.locator('[data-testid=discover-row]').first().click({ button: 'right' })
await T('discover-sel-put').click()
await pause()
check((await T('discover-put').count()) === 1 && (await page.evaluate(() => !!document.activeElement?.closest('[data-testid=discover-put]'))), `右键 → 加入 list，0.3 秒后弹窗开着、焦点在弹窗里（${await active()}）`)
await page.keyboard.press('Escape')
await clean()

