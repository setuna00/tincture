await T('gallery-cell').first().click({ button: 'right' })
await T('gallery-menu-rename').click()
await pause()
check((await T('gallery-name-input').count()) === 1 && (await active()) === 'gallery-name-input', `图片右键 → 重命名，0.3 秒后右栏名字框有焦点（${await active()}）`)
await page.keyboard.press('Escape')
await clean()

console.log('3. 问 AI')
await page.evaluate(
  async ({ url, key }) => {
    const { useAi } = await window.__peImport('/src/store/ai.ts')
    useAi.getState().saveService({ id: 'ai_fake', preset: 'custom', url, model: 'fake-model', key })
    useAi.getState().setCurrent('ai_fake')
  },
  { url: fake.url, key: GOOD_KEY },
)
await page.goto(base)
await T('status-bar').waitFor()
await T('tab').first().click()
await T('rail-ai').click()
