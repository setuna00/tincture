await page.getByRole('menuitem', { name: '新对话' }).click()
await pause()
check((await active()) === 'ai-chat-input', `「新对话」后焦点在输入框（${await active()}）`)
await page.keyboard.type('hello')
check((await T('ai-chat-input').inputValue()) === 'hello', '直接打字进了输入框')

check(!errors.length, `没有报错${errors.length ? `：${errors.slice(0, 3).join(' | ')}` : ''}`)
await browser.close()
await fake.close?.()
console.log(fails.length ? `\n${fails.length} FAIL` : '\nall ok')
process.exit(fails.length ? 1 : 0)
