  const body = WIKI[name]
  return body ? r.fulfill({ status: 200, contentType: 'application/json', body: JSON.stringify({ title: name, body, is_deleted: false }) }) : r.fulfill({ status: 404, contentType: 'application/json', body: '{"success":false}' })
