import { chromium } from '@playwright/test'
import { seedStacks } from './gallery-stacks-seed.mjs'
import { E2E_URL, isolate, resetStore, stored, settled } from './store.mjs'

const theme = process.argv[2] ?? 'light'
const browser = await chromium.launch()
const errors = []
const fails = []
const check = (ok, msg) => (ok ? console.log('ok  ', msg) : (fails.push(msg), console.log('FAIL', msg)))

async function open(width = 1440) {
  const context = await browser.newContext({ viewport: { width, height: 900 } })
  await isolate(context)
  await context.route(/novelai\.net/, (r) => r.abort())
  const page = await context.newPage()
  page.on('console', (m) => m.type() === 'error' && !/novelai\.net|Failed to load resource/.test(m.text()) && errors.push(m.text()))
  page.on('pageerror', (e) => errors.push(String(e)))
  await page.goto(E2E_URL)
  await page.getByTestId('app-rail').waitFor()
  await resetStore(page, { theme })
  await page.reload()
  await page.waitForSelector('[data-testid=app-rail]')
  await seedStacks(page)
  await page.goto(`${E2E_URL}#/gallery`)
  await page.reload()
  await page.waitForSelector('[data-testid=gallery-stack]', { timeout: 30000 })
  await page.waitForTimeout(800)
  await page.addStyleTag({ content: '[data-sonner-toaster]{visibility:hidden!important}' })
  return page
}
